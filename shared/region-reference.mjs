export function regionReference(platform, country, now = Date.now()) {
  if (platform !== "gpt" || !/^[A-Z]{2}$/.test(country || "")) return null;
  const reference = GPT_REGION_REFERENCE;
  const age = now - Date.parse(reference.verifiedAt);
  if (!Number.isFinite(age) || age < 0) return null;
  const membership = countryMembership(reference.countries, country);
  const expired = age > reference.maxAgeDays * 86400000;
  return {
    kind: "bundled-official-reference",
    product: reference.product,
    source: reference.source,
    verifiedAt: reference.verifiedAt,
    maxAgeDays: reference.maxAgeDays,
    expired,
    listed: expired ? null : membership.listed,
    restricted: membership.restricted,
    limitation:
      "随软件附带的官方名单参考，不能替代本次实时核验；过期后不再用于地区对照。",
  };
}
